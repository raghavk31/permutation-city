// Build app/api/_corpus.ts from /corpus (`npm run corpus`, through scripts/write-corpus.ts).
// The function can't read ../corpus on Vercel (the root directory is app/), so the snippets
// ship as a module. test/ui/brief.test.ts fails if this file is out of date.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { corpusSnippets, type Snippet } from "../brief/chunk";

export const CORPUS = join(__dirname, "..", "..", "corpus");
export const OUT = join(__dirname, "..", "api", "_corpus.ts");

function files(dir: string): string[] {
  return readdirSync(dir).sort().flatMap((f) => {
    const p = join(dir, f);
    if (f.startsWith("_") || f.startsWith(".")) return [];
    if (statSync(p).isDirectory()) return files(p);
    return f.endsWith(".md") && f !== "SOURCES.md" ? [p] : [];
  });
}

export function buildCorpus(): { snippets: Snippet[]; files: string[] } {
  const fs = files(CORPUS);
  const snippets = fs.flatMap((f) => corpusSnippets(readFileSync(f, "utf8")));
  const ids = new Set<string>();
  for (const s of snippets) {
    if (ids.has(s.id)) throw new Error(`duplicate snippet id ${s.id}`);
    ids.add(s.id);
  }
  return { snippets, files: fs.map((f) => relative(join(CORPUS, ".."), f).replace(/\\/g, "/")) };
}

export function render(): string {
  const { snippets, files: fs } = buildCorpus();
  return "// Generated by `npm run corpus` from /corpus. Don't edit by hand.\n"
    + `// ${fs.length} files, ${snippets.length} snippets.\n`
    + 'import type { Snippet } from "../brief/chunk.js";\n\n'
    + `export const CORPUS: Snippet[] = ${JSON.stringify(snippets, null, 1)};\n`;
}

export function writeCorpus() {
  writeFileSync(OUT, render(), "utf8");
  console.log(`wrote ${relative(process.cwd(), OUT)}`);
}
