/** The seeds of a public space's two drawings: its dry day (a space that holds water only in a
 *  storm is drawn empty) and, when it holds water at all, its wet day (`fill` deep). */
export function daySeeds(p: Precedent): { dry: Params; wet?: Params } {
  const o = p.open;
  if (!o || o.holds === "never" || !o.fill) return { dry: p.seed };
  const empty = o.holds === "storm" && p.seed.arrangement === "sunken";
  return { dry: empty ? { ...p.seed, water: 0 } : p.seed, wet: { ...p.seed, fill: o.fill } };
}
